import { create } from 'zustand';
import { v4 as uuidv4 } from 'uuid';
import type { HighlightReel, FilmClip } from '@/domain/types';
import { highlightReelRepo, filmClipRepo } from '@/db/database';

interface HighlightStore {
  reels: HighlightReel[];
  activeReel: HighlightReel | null;
  reelClips: FilmClip[];

  loadReelsForTeam(teamId: string): Promise<void>;
  setActiveReel(id: string | null): Promise<void>;

  createReel(data: {
    teamId: string;
    title: string;
    description: string;
    clipIds: string[];
    playerId?: string;
    matchId?: string;
    isAutoGenerated?: boolean;
  }): Promise<HighlightReel>;
  updateReel(reel: HighlightReel): Promise<void>;
  deleteReel(id: string): Promise<void>;

  addClipToReel(reelId: string, clipId: string): Promise<void>;
  removeClipFromReel(reelId: string, clipId: string): Promise<void>;
  reorderClips(reelId: string, clipIds: string[]): Promise<void>;

  generatePlayerReel(teamId: string, playerId: string, playerName: string): Promise<HighlightReel>;
}

export const useHighlightStore = create<HighlightStore>((set, get) => ({
  reels: [],
  activeReel: null,
  reelClips: [],

  async loadReelsForTeam(teamId: string) {
    const reels = await highlightReelRepo.getByTeam(teamId);
    set({ reels: reels.sort((a, b) => b.createdAt.localeCompare(a.createdAt)) });
  },

  async setActiveReel(id: string | null) {
    if (!id) {
      set({ activeReel: null, reelClips: [] });
      return;
    }
    const reel = get().reels.find((r) => r.id === id) || (await highlightReelRepo.get(id));
    if (reel) {
      const clips: FilmClip[] = [];
      for (const clipId of reel.clipIds) {
        const clip = await filmClipRepo.get(clipId);
        if (clip) clips.push(clip);
      }
      set({ activeReel: reel, reelClips: clips });
    }
  },

  async createReel(data) {
    const now = new Date().toISOString();
    const reel: HighlightReel = {
      id: uuidv4(),
      teamId: data.teamId,
      title: data.title,
      description: data.description,
      clipIds: data.clipIds,
      playerId: data.playerId,
      matchId: data.matchId,
      isAutoGenerated: data.isAutoGenerated || false,
      createdAt: now,
      updatedAt: now,
    };
    await highlightReelRepo.put(reel);
    set({ reels: [reel, ...get().reels] });
    return reel;
  },

  async updateReel(reel) {
    const updated = { ...reel, updatedAt: new Date().toISOString() };
    await highlightReelRepo.put(updated);
    set({
      reels: get().reels.map((r) => (r.id === updated.id ? updated : r)),
      activeReel: get().activeReel?.id === updated.id ? updated : get().activeReel,
    });
  },

  async deleteReel(id) {
    await highlightReelRepo.delete(id);
    set({
      reels: get().reels.filter((r) => r.id !== id),
      activeReel: get().activeReel?.id === id ? null : get().activeReel,
      reelClips: get().activeReel?.id === id ? [] : get().reelClips,
    });
  },

  async addClipToReel(reelId, clipId) {
    const reel = get().reels.find((r) => r.id === reelId);
    if (!reel || reel.clipIds.includes(clipId)) return;
    const updated = { ...reel, clipIds: [...reel.clipIds, clipId], updatedAt: new Date().toISOString() };
    await highlightReelRepo.put(updated);
    const clip = await filmClipRepo.get(clipId);
    set({
      reels: get().reels.map((r) => (r.id === updated.id ? updated : r)),
      activeReel: get().activeReel?.id === updated.id ? updated : get().activeReel,
      reelClips: get().activeReel?.id === updated.id && clip
        ? [...get().reelClips, clip]
        : get().reelClips,
    });
  },

  async removeClipFromReel(reelId, clipId) {
    const reel = get().reels.find((r) => r.id === reelId);
    if (!reel) return;
    const updated = {
      ...reel,
      clipIds: reel.clipIds.filter((id) => id !== clipId),
      updatedAt: new Date().toISOString(),
    };
    await highlightReelRepo.put(updated);
    set({
      reels: get().reels.map((r) => (r.id === updated.id ? updated : r)),
      activeReel: get().activeReel?.id === updated.id ? updated : get().activeReel,
      reelClips: get().activeReel?.id === updated.id
        ? get().reelClips.filter((c) => c.id !== clipId)
        : get().reelClips,
    });
  },

  async reorderClips(reelId, clipIds) {
    const reel = get().reels.find((r) => r.id === reelId);
    if (!reel) return;
    const updated = { ...reel, clipIds, updatedAt: new Date().toISOString() };
    await highlightReelRepo.put(updated);
    const orderedClips: FilmClip[] = [];
    for (const id of clipIds) {
      const c = get().reelClips.find((clip) => clip.id === id);
      if (c) orderedClips.push(c);
    }
    set({
      reels: get().reels.map((r) => (r.id === updated.id ? updated : r)),
      activeReel: get().activeReel?.id === updated.id ? updated : get().activeReel,
      reelClips: get().activeReel?.id === updated.id ? orderedClips : get().reelClips,
    });
  },

  async generatePlayerReel(teamId, playerId, playerName) {
    const clips = await filmClipRepo.getByPlayer(playerId);
    const highlights = clips.filter((c) => c.tag === 'highlight' || c.tag === 'serve' || c.tag === 'rally');
    const sorted = highlights.sort((a, b) => a.startSeconds - b.startSeconds);

    const now = new Date().toISOString();
    const reel: HighlightReel = {
      id: uuidv4(),
      teamId,
      title: `${playerName} Highlights`,
      description: `Auto-generated highlight reel for ${playerName} (${sorted.length} clips)`,
      clipIds: sorted.map((c) => c.id),
      playerId,
      isAutoGenerated: true,
      createdAt: now,
      updatedAt: now,
    };
    await highlightReelRepo.put(reel);
    set({ reels: [reel, ...get().reels] });
    return reel;
  },
}));
